package com.kflow.erp.hr.api;

public final class HrFailure extends RuntimeException {
    public enum Code {
        INVALID_EMPLOYEE_NO, INVALID_DISPLAY_NAME, INVALID_ASSIGNMENT_REASON, INVALID_REFERENCE,
        INVALID_DATE, UNSUPPORTED_JOINED_ON, INVALID_PAGE, INVALID_EMPLOYMENT_STATUS,
        TRANSACTION_BOUNDARY_VIOLATION, EMPLOYEE_NOT_FOUND, EMPLOYEE_NO_CONFLICT,
        ASSIGNMENT_PERIOD_CONFLICT, HR_ASSIGNMENT_INTEGRITY_VIOLATION,
        INVALID_EXPECTED_VERSION, UNSUPPORTED_ASSIGNMENT_DATE, VERSION_CONFLICT,
        EMPLOYEE_TERMINATED, EMPLOYMENT_STATE_UNSUPPORTED, HR_TIMELINE_CHANGE_UNSUPPORTED,
        ASSIGNMENT_UNCHANGED, SAME_DAY_ASSIGNMENT_CHANGE_UNSUPPORTED,
        INVALID_TERMINATION_REASON, UNSUPPORTED_TERMINATION_DATE, ALREADY_TERMINATED,
        SAME_DAY_TERMINATION_UNSUPPORTED, SAME_DAY_ASSIGNMENT_TERMINATION_UNSUPPORTED,
        EMPLOYEE_COMPANY_MISMATCH, ON_LEAVE_ACCOUNT_LINK_UNSUPPORTED, ON_LEAVE_ROLE_GRANT_UNSUPPORTED, ON_LEAVE_CREDENTIAL_UNSUPPORTED, ON_LEAVE_LOGIN_UNSUPPORTED, EMPLOYMENT_DATE_UNSUPPORTED, HR_DATA_INTEGRITY_ERROR
    }
    private final Code code;
    public HrFailure(Code code) { super(code.name()); this.code = code; }
    public HrFailure(Code code, Throwable cause) { super(code.name(), cause); this.code = code; }
    public Code code() { return code; }
}
