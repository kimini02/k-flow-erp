export function accountingFixture(key: string, r: RecordData, i: number) {
  r.partner = "";
  if (key === "accounts") {
    const account = accountNames[i % accountNames.length];
    r.title = account.slice(5);
    r.values.code = account.slice(0, 4);
    r.values.category =
      account[0] === "1"
        ? "자산"
        : account[0] === "2"
          ? "부채"
          : account[0] === "3"
            ? "자본"
            : account[0] === "4"
              ? "수익"
              : "비용";
    r.values.normal = ["자산", "비용"].includes(String(r.values.category))
      ? "차변"
      : "대변";
    r.status = "사용중";
    r.amount = 0;
  }
  if (key === "journals") {
    // JE-0001 is the newest posted entry; JE-0024 stays a draft for review.
    const entry = JOURNAL_SEED[i];
    if (entry) {
      const [day, title, category, partner, lines] = entry;
      r.date = `2026-09-${day}`;
      r.dueDate = r.date;
      r.title = title;
      r.partner = partner;
      r.owner = "이회계팀장";
      r.values.category = category;
      r.journal = lines.map(([account, debit, credit]) => ({
        account,
        debit,
        credit,
      }));
      r.amount = r.journal.reduce((n, l) => n + l.debit, 0);
      r.status = i === 23 ? "작성중" : "전기완료";
    }
  }
  if (key === "fiscal-periods") {
    r.title = `2026년 ${i + 1}월`;
    r.date = `2026-${String(i + 1).padStart(2, "0")}-01`;
    r.dueDate = `2026-${String(i + 1).padStart(2, "0")}-${[31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31][i]}`;
    r.values.journalCount = i === 8 ? 23 : 0;
    r.status = i < 8 ? "마감" : "진행중";
    r.amount = 0;
  }
}
